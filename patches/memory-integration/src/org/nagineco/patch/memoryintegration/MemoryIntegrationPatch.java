package org.nagineco.patch.memoryintegration;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import java.util.regex.*;

/**
 * Standalone Java 21 patch. Reads 24 individual Markdown journals and writes
 * one shared, attributed memory index. It never edits source journals or the
 * player's authoritative nao_personality.md.
 */
public final class MemoryIntegrationPatch {
    private static final Pattern EVENT = Pattern.compile(
        "^- day=(\\d+) tick=(\\d+) position=\\(([^)]*)\\) action=([A-Z_]+) emotion=([A-Z_]+) reason=([A-Z_]+)\\s*$");
    private static final Pattern PREFERENCE = Pattern.compile(
        "^- preference\\.([a-z_]+):\\s*(\\d+)\\s*$");
    private static final List<String> REASONS =
        List.of("none", "explore", "build", "collect", "safety", "social");
    private static final Set<String> MOVES =
        Set.of("STAY", "NORTH", "SOUTH", "WEST", "EAST");
    private static final Set<String> EMOTIONS =
        Set.of("NEUTRAL", "HAPPY", "CURIOUS", "AFRAID", "ANGRY", "SAD");

    private record Memory(int nao, int day, int tick, String position,
                          String action, String emotion, String reason) {}

    public static void main(String[] args) throws Exception {
        if (args.length != 1) {
            System.err.println("Usage: java ...MemoryIntegrationPatch <server-memory-directory>");
            System.exit(2);
        }
        String result = integrate(Path.of(args[0]));
        System.out.println(result);
    }

    public static String integrate(Path memoryDirectory) throws IOException {
        Path dir = memoryDirectory.toAbsolutePath().normalize();
        if (!Files.isDirectory(dir)) throw new IOException("Not a directory: " + dir);
        Path personality = dir.resolve("nao_personality.md");
        if (!Files.isRegularFile(personality))
            throw new IOException("Missing shared personality: " + personality);
        Map<String,Integer> preferences = readPreferences(personality);
        List<Memory> events = new ArrayList<>();
        int count = 0;
        while (count < 256 && Files.isRegularFile(dir.resolve(String.format(Locale.ROOT, "nao_%02d.md", count + 1)))) count++;
        if (count == 0) throw new IOException("No Nao memories");
        int[] perNao = new int[count];
        int invalid = 0;
        for (int i = 1; i <= count; i++) {
            Path file = dir.resolve(String.format(Locale.ROOT, "nao_%02d.md", i));
            if (!Files.isRegularFile(file))
                throw new IOException("Missing individual memory: " + file);
            Set<String> unique = new HashSet<>();
            for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
                if (!line.startsWith("- day=")) continue;
                Matcher match = EVENT.matcher(line);
                if (!match.matches()) { invalid++; continue; }
                String action = match.group(4), emotion = match.group(5);
                String reason = match.group(6).toLowerCase(Locale.ROOT);
                if (!MOVES.contains(action) || !EMOTIONS.contains(emotion)
                    || !REASONS.contains(reason)) { invalid++; continue; }
                int day, tick;
                try {
                    day = Integer.parseInt(match.group(1));
                    tick = Integer.parseInt(match.group(2));
                } catch (NumberFormatException e) { invalid++; continue; }
                if (day < 1 || tick < 0 || tick >= 24000) { invalid++; continue; }
                if (!unique.add(line)) continue;
                events.add(new Memory(i, day, tick, match.group(3), action, emotion, reason));
                perNao[i-1]++;
            }
        }
        events.sort(Comparator.comparingInt(Memory::day)
            .thenComparingInt(Memory::tick).thenComparingInt(Memory::nao));
        StringBuilder output = new StringBuilder();
        output.append("# Nao — integrated memory\n\n")
            .append("Generated by Memory Integration Patch. This is a shared *index*, not a replacement for the personal memories.\n")
            .append("Personality remains authoritative in `nao_personality.md`.\n")
            .append("Events preserve their original owner; identical actions by different Nao are not merged.\n\n")
            .append("## Shared personality affinity snapshot\n\n");
        for (String reason : REASONS)
            output.append("- preference.").append(reason).append(": ")
                .append(preferences.get(reason)).append("\n");
        output.append("\n## Contributions\n\n");
        for (int i=0;i<count;i++)
            output.append("- Nao ").append(String.format(Locale.ROOT,"%02d",i+1))
                .append(": ").append(perNao[i]).append(" events\n");
        output.append("\n## Integrated events\n\n");
        for (Memory m : events)
            output.append("- nao=").append(String.format(Locale.ROOT,"%02d",m.nao))
                .append(" day=").append(m.day).append(" tick=").append(m.tick)
                .append(" position=(").append(m.position).append(")")
                .append(" action=").append(m.action)
                .append(" emotion=").append(m.emotion)
                .append(" reason=").append(m.reason.toUpperCase(Locale.ROOT))
                .append("\n");
        output.append("\n## Validation\n\n- rejected entries: ").append(invalid).append("\n");
        Path target = dir.resolve("nao_integrated_memory.md");
        Path temp = Files.createTempFile(dir, "nao-integrated-", ".tmp");
        try {
            Files.writeString(temp, output.toString(), StandardCharsets.UTF_8);
            try {
                Files.move(temp, target, StandardCopyOption.ATOMIC_MOVE,
                    StandardCopyOption.REPLACE_EXISTING);
            } catch (AtomicMoveNotSupportedException e) {
                Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING);
            }
        } finally { Files.deleteIfExists(temp); }
        return String.format(Locale.ROOT, "Integrated %d memories from %d Nao; rejected %d; output %s",
            events.size(), count, invalid, target);
    }

    private static Map<String,Integer> readPreferences(Path path) throws IOException {
        Map<String,Integer> preferences = new LinkedHashMap<>();
        for (String line : Files.readAllLines(path, StandardCharsets.UTF_8)) {
            Matcher m = PREFERENCE.matcher(line);
            if (!m.matches()) continue;
            if (!REASONS.contains(m.group(1))) continue;
            int value = Integer.parseInt(m.group(2));
            if (value < 0 || value > 10)
                throw new IOException("Preference out of range: " + line);
            preferences.put(m.group(1), value);
        }
        for (String reason : REASONS)
            if (!preferences.containsKey(reason))
                throw new IOException("Missing preference." + reason + " in " + path);
        return preferences;
    }
}
